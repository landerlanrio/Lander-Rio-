#!/usr/bin/env python3
"""Read-only indexability gate; local by default, explicit --live for HTTP audit.

The policy is a reviewed inventory, never regenerated by this checker.
Technical eligibility is not proof of Google indexing or Ahrefs history.
"""
from __future__ import annotations
import argparse
import concurrent.futures
import fnmatch
import json
import re
import sys
from datetime import datetime, timezone
from html.parser import HTMLParser
from pathlib import Path
from urllib.error import HTTPError, URLError
from urllib.parse import urljoin, urlsplit
from urllib.request import Request, urlopen
from urllib.robotparser import RobotFileParser
from xml.etree import ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]


class Page(HTMLParser):
    def __init__(self, text):
        super().__init__(convert_charrefs=True)
        self.canonicals = []
        self.directives = []
        self.feed(text)

    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        if tag == 'link' and 'canonical' in attrs.get('rel', '').lower().split():
            self.canonicals.append(attrs.get('href', ''))
        if tag == 'meta' and attrs.get('name', '').lower() in ('robots', 'googlebot'):
            self.directives.extend(re.split(r'[\s,]+', attrs.get('content', '').lower()))


def header_directives(values):
    result = []
    for value in values:
        scope = '*'
        for item in value.lower().split(','):
            item = item.strip()
            if ':' in item:
                prefix, rest = item.split(':', 1)
                if prefix.strip() not in ('unavailable_after', 'max-snippet', 'max-image-preview', 'max-video-preview'):
                    scope, item = prefix.strip(), rest.strip()
            if scope in ('*', 'googlebot'):
                result.extend(item.split())
    return result


def netlify_headers(text, route):
    values, pattern = [], None
    for line in text.splitlines():
        if not line.strip() or line.lstrip().startswith('#'):
            continue
        if not line[0].isspace():
            pattern = line.strip()
        elif pattern and fnmatch.fnmatchcase(route, pattern):
            key, _, value = line.strip().partition(':')
            if key.lower() == 'x-robots-tag':
                values.append(value.strip())
    return values


def sitemap_urls(text):
    root = ET.fromstring(text)
    return [node.text.strip() for node in root.iter()
            if node.tag.split('}')[-1] == 'loc' and node.text]


def inspect(row, text, headers, status, robots, sitemap, final_url=None):
    page = Page(text)
    directives = set(page.directives + header_directives(headers))
    noindex = bool(directives & {'noindex', 'none'})
    crawlable = robots.can_fetch('Googlebot', row['canonical'])
    errors = []
    if status not in row.get('http_statuses', [200]):
        errors.append('unexpected_http_status')
    if page.canonicals != [row['canonical']]:
        errors.append('canonical_mismatch')
    if final_url and final_url != row['canonical']:
        errors.append('unexpected_redirect')
    if noindex == row['indexable']:
        errors.append('unexpected_noindex' if noindex else 'intentional_noindex_removed')
    if row['indexable'] and not crawlable:
        errors.append('indexable_page_blocked_by_robots')
    if (row['canonical'] in sitemap) != row['indexable']:
        errors.append('sitemap_policy_mismatch')
    return {'path': row['path'], 'canonical': row['canonical'], 'status': status,
            'expected_indexable': row['indexable'], 'noindex': noindex,
            'crawlable': crawlable, 'errors': errors}


def fetch(url):
    request = Request(url, headers={'User-Agent': 'LanderRio-ReadOnlyQA/1.0'})
    try:
        response = urlopen(request, timeout=20)
    except HTTPError as error:
        response = error
    with response:
        # This audit only retrieves HTML and control files, never image originals.
        data = response.read(2_000_001)
        if len(data) > 2_000_000:
            raise ValueError('response exceeds 2 MB limit')
        return response.status, data.decode('utf-8'), response.headers.get_all('X-Robots-Tag', []), response.geturl()


def audit(site, policy, live=False):
    errors, rows = [], []
    declared = {row['path'] for row in policy['pages']}
    actual = {p.relative_to(site).as_posix() for p in site.rglob('*.html')}
    if declared != actual or len(declared) != len(policy['pages']):
        errors.append({'inventory_mismatch': {'undeclared': sorted(actual - declared),
                                            'missing': sorted(declared - actual)}})
    origin = policy['origin']
    if live:
        status_r, robots_text, _, _ = fetch(origin + '/robots.txt')
        status_s, sitemap_text, _, _ = fetch(origin + '/sitemap.xml')
        if status_r != 200 or status_s != 200:
            errors.append({'control_file_status': [status_r, status_s]})
    else:
        robots_text = (site / 'robots.txt').read_text()
        sitemap_text = (site / 'sitemap.xml').read_text()
    urls = sitemap_urls(sitemap_text)
    expected_urls = {row['canonical'] for row in policy['pages'] if row['indexable']}
    if len(urls) != len(set(urls)) or set(urls) != expected_urls:
        errors.append({'sitemap_inventory_mismatch': {'extra': sorted(set(urls) - expected_urls),
                                                     'missing': sorted(expected_urls - set(urls)),
                                                     'duplicates': len(urls) - len(set(urls))}})
    robots = RobotFileParser(); robots.parse(robots_text.splitlines())
    header_text = (site / '_headers').read_text()

    def check(row):
        try:
            url = row['canonical']
            if urlsplit(url).netloc != urlsplit(origin).netloc or not url.startswith(origin + '/'):
                raise ValueError('policy canonical outside declared origin')
            if live:
                status, text, headers, final = fetch(url)
            else:
                status, text, headers, final = 200, (site / row['path']).read_text(), netlify_headers(header_text, urlsplit(url).path), None
            return inspect(row, text, headers, status, robots, set(urls), final)
        except (OSError, ValueError, URLError) as error:
            return {'path': row['path'], 'errors': ['audit_unavailable'], 'detail': str(error)[:200]}

    if live:
        with concurrent.futures.ThreadPoolExecutor(max_workers=6) as pool:
            rows = list(pool.map(check, policy['pages']))
    else:
        rows = [check(row) for row in policy['pages']]
    return {'status': 'PASS' if not errors and not any(r['errors'] for r in rows) else 'FAIL',
            'checked_at': datetime.now(timezone.utc).isoformat(), 'mode': 'live_http' if live else 'local',
            'baseline_commit': policy['baseline_commit'], 'pages_checked': len(rows),
            'expected_indexable': len(expected_urls), 'expected_noindex': len(rows)-len(expected_urls),
            'errors': errors, 'pages': rows,
            'limits': 'Technical directive check only. Does not prove search-engine indexing, crawl-history deltas, traffic or conversion.'}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--site', type=Path, default=ROOT / 'site')
    parser.add_argument('--policy', type=Path, default=ROOT / 'content/indexability-policy.json')
    parser.add_argument('--live', action='store_true', help='Explicit read-only requests to the policy origin; never POSTs or edits.')
    parser.add_argument('--out', type=Path)
    args = parser.parse_args()
    try:
        result = audit(args.site, json.loads(args.policy.read_text()), args.live)
    except (OSError, ValueError, ET.ParseError) as error:
        result = {'status': 'FAIL', 'errors': [str(error)]}
    if args.out:
        args.out.parent.mkdir(parents=True, exist_ok=True)
        args.out.write_text(json.dumps(result, ensure_ascii=False, indent=2) + '\n')
    print(json.dumps({k: v for k, v in result.items() if k != 'pages'}, ensure_ascii=False, indent=2))
    for row in result.get('pages', []):
        if row['errors']:
            print(json.dumps(row, ensure_ascii=False))
    return 0 if result['status'] == 'PASS' else 1


if __name__ == '__main__':
    sys.exit(main())
